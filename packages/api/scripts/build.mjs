// Builds the package into dist/: the helpers as ES module and CommonJS, and the declarations,
// bundled with the extension API's types into one file. Run with `pnpm build` in packages/api.
//
// Exported for declarations.test.ts, which builds into a folder of its own.
import { execFileSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { build as esbuild } from 'esbuild';
import { bundleDeclarations } from './declarations.mjs';

const packageDir = resolve(import.meta.dirname, '..');
const tsc = join(dirname(createRequire(import.meta.url).resolve('typescript/package.json')), 'bin/tsc');

const HEADER = `// The types of Waypoint's extension API and of the helpers in this package. Generated by
// packages/api/scripts/build.mjs from the app's src/shared/extension-api.ts, src/shared/types.ts
// and the helpers' source; don't edit it by hand.

`;

/**
 * Runs tsc in `dir` with the given tsconfig, and throws with its output if it finds errors.
 * @param {string} dir
 * @param {object} config
 */
export function typecheck(dir, config) {
  const project = join(dir, 'tsconfig.json');
  writeFileSync(project, JSON.stringify(config, null, 2));
  try {
    execFileSync(process.execPath, [tsc, '-p', project], { stdio: 'pipe' });
  } catch (error) {
    throw new Error(`tsc failed:\n${output(error)}`);
  }
}

/**
 * What a program that failed printed.
 * @param {unknown} error
 */
function output(error) {
  const { stdout = '', stderr = '' } = /** @type {{ stdout?: Buffer | string, stderr?: Buffer | string }} */ (error);
  return `${stdout}${stderr}`;
}

/**
 * The declarations of src/index.ts, bundled.
 * @returns {string}
 */
export function declarations() {
  const emitted = mkdtempSync(join(tmpdir(), 'waypoint-api-dts-'));
  try {
    execFileSync(process.execPath, [tsc, '-p', join(packageDir, 'tsconfig.build.json'), '--outDir', emitted], {
      stdio: 'pipe',
    });
    return bundleDeclarations(join(emitted, 'packages/api/src/index.d.ts'), { root: emitted, header: HEADER });
  } catch (error) {
    if (output(error)) throw new Error(`tsc failed:\n${output(error)}`);
    throw error;
  } finally {
    rmSync(emitted, { recursive: true, force: true });
  }
}

/**
 * Checks that the bundled declarations stand on their own: no other files, no Node types.
 * @param {string} file
 */
export function checkDeclarations(file) {
  const dir = mkdtempSync(join(tmpdir(), 'waypoint-api-check-'));
  try {
    typecheck(dir, {
      compilerOptions: { strict: true, noEmit: true, skipLibCheck: false, types: [], lib: ['ES2023'] },
      files: [file],
    });
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

/**
 * Builds the package into `outDir`, and returns it.
 * @param {string} [outDir]
 */
export async function build(outDir = join(packageDir, 'dist')) {
  rmSync(outDir, { recursive: true, force: true });
  mkdirSync(outDir, { recursive: true });
  /** @type {import('esbuild').BuildOptions} */
  const common = {
    entryPoints: [join(packageDir, 'src/index.ts')],
    bundle: true,
    platform: 'neutral',
    target: 'es2022',
    logLevel: 'warning',
  };
  await esbuild({ ...common, format: 'esm', outfile: join(outDir, 'index.js') });
  await esbuild({ ...common, format: 'cjs', outfile: join(outDir, 'index.cjs') });
  const types = declarations();
  // The same declarations describe both: there's nothing in them that differs.
  writeFileSync(join(outDir, 'index.d.ts'), types);
  writeFileSync(join(outDir, 'index.d.cts'), types);
  checkDeclarations(join(outDir, 'index.d.ts'));
  return outDir;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const outDir = await build();
  console.log(`Built ${outDir}`);
}
